const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(module,filename)=>module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,filename);
const {places}=require('../data/places.ts');
const {makeSavedDayPlan,parseSavedDayPlan,SAVED_DAY_PLAN_KEY}=require('../lib/savedDayPlan.ts');
assert.equal(SAVED_DAY_PLAN_KEY,'le-golfe-day-plan-v1');
const ids=places.slice(0,3).map(p=>p.id);
const record=makeSavedDayPlan([ids[0],ids[1],ids[0],ids[2],'unknown'], 'half',places,'2026-10-15T12:00:00.000Z');
assert.deepEqual(record.placeIds,ids);
assert.deepEqual(parseSavedDayPlan(JSON.stringify(record),places),record);
assert.equal(parseSavedDayPlan('{invalid',places),null);
assert.equal(parseSavedDayPlan(JSON.stringify({version:2,format:'half',placeIds:ids,updatedAt:'now'}),places),null);
assert.equal(parseSavedDayPlan(JSON.stringify({version:1,format:'half',placeIds:['bad'],updatedAt:'now'}),places),null);
assert.equal(makeSavedDayPlan([], 'full',places,'2026-10-15'),null);
const ask=fs.readFileSync('app/[locale]/ask/page.tsx','utf8');
const saved=fs.readFileSync('app/[locale]/saved/page.tsx','utf8');
assert.ok(ask.includes('EditableAskPlan'));
assert.ok(saved.includes('<SavedDayPlanSection locale={locale}/>'));
const editor=fs.readFileSync('components/EditableAskPlan.tsx','utf8');
assert.ok(editor.includes('localStorage.setItem(SAVED_DAY_PLAN_KEY'));
assert.ok(editor.includes('setIds('));
console.log('Saved plan storage version, validation, deduplication and integration passed');
